#!/usr/bin/env python3
"""Check the odoo skill against the facts extracted from the matching Odoo source.

    check_skill.py FACTS.json SKILL_DIR [--write]

- references/version-facts.md must be exactly the rendering of FACTS (--write
  regenerates it);
- every API the references use must exist in that Odoo version: @api.X,
  models.X, fields.X, `from odoo.tests import ...`, names imported from
  @odoo/owl, route types;
- the list view tag and the security CSV format must match the version.
references/version-notes.md is exempt: it describes what changed, so it names
old and new API on purpose.
"""

import argparse
import json
import re
import sys
from pathlib import Path

EXEMPT = {"version-notes.md", "version-facts.md"}
FENCE_RE = re.compile(r"```[\w-]*\n(.*?)```", re.S)
# the names of `from x import ...`: a parenthesized list may span lines, otherwise one line
IMPORTED = r"(\([^)]*\)|[\w ,]+)"


def render_facts(facts):
    sec = facts["security"]
    lines = [
        f"# Odoo {facts['odoo_version']}: version facts",
        "",
        "<!-- Generated by tools/odoo-skill-extract/check_skill.py --write from the Odoo source."
        " Do not edit by hand. -->",
        "",
        f"Source: github.com/odoo/odoo branch {facts['odoo_version']}"
        + (f", commit {facts['source_commit']}" if facts.get("source_commit") else "") + ".",
        "",
        "| Fact | Value |",
        "|---|---|",
        f"| List view tag | `<{facts['list_view_tag']}>` |",
        f"| Access rights model | `{sec['model']}` in `security/{sec['csv']}` |",
        f"| Access CSV header | `{sec['header']}` |",
        f"| Record rules model (ir.rule) | {'yes' if sec['record_rules'] else 'no (domain column of ir.access)'} |",
        f"| HTTP route types | {', '.join(f'`{t}`' for t in facts['route_types'])} |",
        f"| OWL version | {facts['owl_version']} |",
        "",
        "## odoo.api decorators",
        ", ".join(f"`@api.{d}`" for d in facts["api_decorators"]),
        "",
        "## odoo.models",
        ", ".join(f"`{n}`" for n in facts["models_exports"] if n[0].isupper() and not n.isupper()),
        "",
        "## Field types (odoo.fields)",
        ", ".join(f"`fields.{c}` ({t})" for c, t in facts["field_types"].items()),
        "",
        "## odoo.tests",
        ", ".join(f"`{n}`" for n in facts["tests_exports"]),
        "",
        "## @odoo/owl exports",
        ", ".join(f"`{n}`" for n in facts["owl_exports"]),
        "",
        "## Manifest keys",
        ", ".join(f"`{k}`" for k in facts["manifest_keys"]),
        "",
        "## View RNG schemas (odoo/addons/base/rng)",
        ", ".join(f"`{f}`" for f in facts["view_rng_files"]),
        "",
        "## Code upgrade steps up to this version (odoo-bin upgrade_code)",
        "\n".join(f"- `{s}`" for s in facts["upgrade_steps"]) or "- none",
        "",
        "## DeprecationWarnings in the core",
        "\n".join(f"- {m}" for m in facts["deprecations"]) or "- none",
        "",
    ]
    return "\n".join(lines)


def code_blocks(text):
    """(start_line, code) of each fenced code block."""
    for match in FENCE_RE.finditer(text):
        yield text.count("\n", 0, match.start()) + 2, match.group(1)


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def check_reference(name, text, facts):
    problems = []

    def bad(pos, msg):
        problems.append(f"{name}:{line_of(text, pos)}: {msg}")

    for m in re.finditer(r"@api\.(\w+)", text):
        if m.group(1) not in facts["api_exports"]:
            bad(m.start(), f"@api.{m.group(1)} does not exist in Odoo {facts['odoo_version']}")
    for m in re.finditer(r"\bmodels\.([A-Z]\w*)", text):
        if m.group(1) not in facts["models_exports"]:
            bad(m.start(), f"models.{m.group(1)} does not exist in Odoo {facts['odoo_version']}")
    for m in re.finditer(r"\bfields\.([A-Z]\w*)", text):
        if m.group(1) not in facts["fields_exports"]:
            bad(m.start(), f"fields.{m.group(1)} does not exist in Odoo {facts['odoo_version']}")
    for module, key in (("fields", "fields_exports"), ("api", "api_exports"),
                        ("models", "models_exports")):
        for m in re.finditer(rf"from odoo\.{module} import {IMPORTED}", text):
            for imported in re.findall(r"\w+", m.group(1)):
                if imported != "as" and imported not in facts[key]:
                    bad(m.start(), f"odoo.{module}.{imported} does not exist in Odoo "
                                   f"{facts['odoo_version']}")
    for m in re.finditer(rf"from odoo\.tests import {IMPORTED}", text):
        for imported in re.findall(r"\w+", m.group(1)):
            if imported not in facts["tests_exports"]:
                bad(m.start(), f"odoo.tests.{imported} does not exist in Odoo "
                               f"{facts['odoo_version']}")
    for m in re.finditer(r"import\s*\{([^}]*)\}\s*from\s*[\"']@odoo/owl[\"']", text):
        for imported in re.findall(r"\b(\w+)\b(?:\s+as\s+\w+)?", m.group(1)):
            if imported != "as" and imported not in facts["owl_exports"]:
                bad(m.start(), f"@odoo/owl does not export {imported} in Odoo "
                               f"{facts['odoo_version']} (OWL {facts['owl_version']})")
    for start, code in code_blocks(text):
        for m in re.finditer(r"""\btype\s*=\s*['"](\w+)['"]""", code):
            before = code[max(0, m.start() - 200):m.start()]
            if "route(" in before and m.group(1) not in facts["route_types"]:
                problems.append(f"{name}:{start + code.count(chr(10), 0, m.start())}: route "
                                f"type='{m.group(1)}' does not exist in Odoo {facts['odoo_version']}")
        other_tag = "tree" if facts["list_view_tag"] == "list" else "list"
        for m in re.finditer(rf"<{other_tag}[\s>/]", code):
            problems.append(f"{name}:{start + code.count(chr(10), 0, m.start())}: <{other_tag}> "
                            f"in a code block; Odoo {facts['odoo_version']} uses "
                            f"<{facts['list_view_tag']}>")
    wrong_csv = "ir.model.access" if facts["security"]["model"] == "ir.access" else "ir.access.csv"
    for m in re.finditer(re.escape(wrong_csv), text):
        bad(m.start(), f"{wrong_csv} is not the access format of Odoo {facts['odoo_version']}")
    return problems


def check(facts, skill_dir, write=False):
    skill_dir = Path(skill_dir)
    problems = []
    skill_md = skill_dir / "SKILL.md"
    if not skill_md.is_file():
        return [f"{skill_md} is missing"]
    head = skill_md.read_text().split("---")[1] if skill_md.read_text().startswith("---") else ""
    if f"Odoo {facts['odoo_version']}" not in head:
        problems.append(f"SKILL.md: the frontmatter must name 'Odoo {facts['odoo_version']}'")
    facts_md = skill_dir / "references" / "version-facts.md"
    expected = render_facts(facts)
    if write:
        facts_md.parent.mkdir(parents=True, exist_ok=True)
        facts_md.write_text(expected)
    elif not facts_md.is_file() or facts_md.read_text() != expected:
        problems.append("references/version-facts.md is out of date: run check_skill.py --write")
    for path in sorted([skill_md, *(skill_dir / "references").glob("*.md")]):
        if path.name in EXEMPT:
            continue
        problems += check_reference(str(path.relative_to(skill_dir)), path.read_text(), facts)
    return problems


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("facts", type=Path)
    p.add_argument("skill_dir", type=Path)
    p.add_argument("--write", action="store_true", help="regenerate references/version-facts.md")
    args = p.parse_args(argv)
    facts = json.loads(args.facts.read_text())
    problems = check(facts, args.skill_dir, args.write)
    for problem in problems:
        print(f"✗ {problem}", file=sys.stderr)
    if problems:
        return 1
    print(f"✓ skill matches Odoo {facts['odoo_version']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
